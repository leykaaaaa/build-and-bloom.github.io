"use client";

import { useEffect, useState } from "react";
import { getAuthHeaders } from "../../../services/authService";

import styles from "../adminPages.module.css";


// =========================================================
// SMALL INLINE ICONS (no extra package needed)
// =========================================================

function Icon({ size = 24, strokeWidth = 2, children }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

const SparklesIcon = ({ size }) => (
  <Icon size={size}>
    <path d="m12 3-1.9 5.8a2 2 0 0 1-1.3 1.3L3 12l5.8 1.9a2 2 0 0 1 1.3 1.3L12 21l1.9-5.8a2 2 0 0 1 1.3-1.3L21 12l-5.8-1.9a2 2 0 0 1-1.3-1.3z" />
  </Icon>
);

const LayersIcon = () => (
  <Icon>
    <path d="m12 2 10 5-10 5L2 7z" />
    <path d="m2 12 10 5 10-5" />
    <path d="m2 17 10 5 10-5" />
  </Icon>
);

const ClipboardIcon = () => (
  <Icon>
    <rect width="8" height="4" x="8" y="2" rx="1" />
    <path d="M16 4h2a2 2 0 0 1 2 2v14a2 2 0 0 1-2 2H6a2 2 0 0 1-2-2V6a2 2 0 0 1 2-2h2" />
    <path d="M12 11h4M12 16h4M8 11h.01M8 16h.01" />
  </Icon>
);

const SearchIcon = () => (
  <Icon size={20}>
    <circle cx="11" cy="11" r="8" />
    <path d="m21 21-4.3-4.3" />
  </Icon>
);


// Classification badge colour
function classificationBadgeClass(status) {
  if (status === "Highly Suitable") {
    return styles.badgeVeg;
  }

  if (status === "Moderately Suitable") {
    return styles.badgeFruit;
  }

  return styles.badgeLow;
}

export default function RecommendationsPage() {
  const [recommendations, setRecommendations] = useState([]);
  const [searchTerm, setSearchTerm] = useState("");
  const [classificationFilter, setClassificationFilter] = useState("");
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchRecommendations = async () => {
      try {
        const response = await fetch(
          "http://localhost:5000/api/recommendations/history",
          {
            headers: getAuthHeaders()
          }
        );

        const result = await response.json();
        console.log("Recommendation API response:", result);

        if (result.success) {
          setRecommendations(result.data);
        }
      } catch (error) {
        console.error(
          "Failed to fetch recommendation history:",
          error
        );
      } finally {
        setLoading(false);
      }
    };

    fetchRecommendations();
  }, []);

  const classifications = [
    ...new Set(
      recommendations
        .map((recommendation) => recommendation.compatibility_level)
        .filter(Boolean)
    ),
  ].sort((a, b) => a.localeCompare(b));

  const filteredRecommendations = recommendations.filter(
    (recommendation) => {
      const search = searchTerm.toLowerCase();

      const matchesSearch = (
        String(recommendation.recommendation_id)
          .toLowerCase()
          .includes(search) ||
        recommendation.location_name
          ?.toLowerCase()
          .includes(search) ||
        recommendation.crop_name
          ?.toLowerCase()
          .includes(search) ||
        recommendation.compatibility_level
          ?.toLowerCase()
          .includes(search) ||
        recommendation.full_name
          ?.toLowerCase()
          .includes(search)
      );

      const matchesClassification =
        !classificationFilter ||
        recommendation.compatibility_level === classificationFilter;

      return matchesSearch && matchesClassification;
    }
  );

  return (
    <div className={styles.adminPage}>
      {/* Header */}
      <div className={styles.pageHeader}>
        <div className={styles.pageHeading}>
          <h1 className={styles.pageTitle}>
            Recommendations
          </h1>

          <p className={styles.pageSubtitle}>
            Monitor crop recommendations generated by the
            compatibility engine.
          </p>
        </div>
      </div>

      {/* Summary Cards */}
      <div className={styles.statGrid}>
        <div className={styles.statBox}>
          <span className={`${styles.statIconBox} ${styles.toneMint}`}>
            <SparklesIcon />
          </span>

          <div className={styles.statText}>
            <span>Recommendation Engine</span>
            <strong>Active</strong>
            <span className={styles.statNote}>
              Compatibility engine is available
            </span>
          </div>
        </div>

        <div className={styles.statBox}>
          <span className={`${styles.statIconBox} ${styles.toneWater}`}>
            <LayersIcon />
          </span>

          <div className={styles.statText}>
            <span>Factors Used</span>
            <strong>7</strong>
            <span className={styles.statNote}>
              Soil, water, sunlight, environment,
              weather, season, and location
            </span>
          </div>
        </div>

        <div className={styles.statBox}>
          <span className={`${styles.statIconBox} ${styles.toneSun}`}>
            <ClipboardIcon />
          </span>

          <div className={styles.statText}>
            <span>Recommendation Records</span>
            <strong>
              {loading ? "..." : recommendations.length}
            </strong>
            <span className={styles.statNote}>
              Saved recommendation history
            </span>
          </div>
        </div>
      </div>

      {/* Search + classification filter */}
      <div className={styles.toolbar}>
        <div className={styles.searchBox}>
          <span className={styles.searchBoxIcon}>
            <SearchIcon />
          </span>

          <label
            htmlFor="recommendation-search"
            className={styles.visuallyHidden}
          >
            Search recommendations
          </label>

          <input
            id="recommendation-search"
            className={styles.searchInput}
            type="search"
            placeholder="Search recommendations..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
          />
        </div>

        <label
          htmlFor="recommendation-classification"
          className={styles.visuallyHidden}
        >
          Filter by classification
        </label>

        <select
          id="recommendation-classification"
          className={styles.filterSelect}
          value={classificationFilter}
          onChange={(e) => setClassificationFilter(e.target.value)}
        >
          <option value="">All classifications</option>

          {classifications.map((classification) => (
            <option key={classification} value={classification}>
              {classification}
            </option>
          ))}
        </select>
      </div>

      {/* Recommendation Table */}
      <section className={styles.tableCard}>
        <div className={styles.tableCardHeader}>
          <h2>Recommendation Results</h2>

          <span className={styles.tableNote}>
            Recommendation history generated by the compatibility engine.
          </span>
        </div>

        <div className={styles.tableScroll}>
          <table className={styles.dataTable}>
            <thead>
              <tr>
                <th scope="col">ID</th>
                <th scope="col">User</th>
                <th scope="col">Location</th>
                <th scope="col">Crop</th>
                <th scope="col">Compatibility Score</th>
                <th scope="col">Classification</th>
                <th scope="col">Date</th>
              </tr>
            </thead>

            <tbody>
              {loading ? (
                <tr>
                  <td colSpan="7" className={styles.emptyRow}>
                    Loading recommendation history...
                  </td>
                </tr>
              ) : filteredRecommendations.length === 0 ? (
                <tr>
                  <td colSpan="7" className={styles.emptyRow}>
                    No recommendations found.
                  </td>
                </tr>
              ) : (
                filteredRecommendations.map(
                  (recommendation) => (
                    <tr
                      key={
                        recommendation.recommendation_id
                      }
                    >
                      <td>
                        {recommendation.recommendation_id}
                      </td>

                      <td>
                        {recommendation.full_name || "Guest"}
                      </td>

                      <td>
                        {recommendation.location_name ||
                          "Unknown"}
                      </td>

                      <td>
                        <span className={styles.cellStrong}>
                          {recommendation.crop_name}
                        </span>
                      </td>

                      <td>
                        <div className={styles.scoreWrap}>
                          <div className={styles.scoreTrack}>
                            <div
                              className={styles.scoreFill}
                              style={{
                                width: `${Math.min(
                                  100,
                                  Math.max(
                                    0,
                                    Number(recommendation.compatibility_score) || 0
                                  )
                                )}%`,
                              }}
                            />
                          </div>

                          <strong className={styles.scoreValue}>
                            {recommendation.compatibility_score}%
                          </strong>
                        </div>
                      </td>

                      <td>
                        <span
                          className={`${styles.badge} ${classificationBadgeClass(
                            recommendation.compatibility_level
                          )}`}
                        >
                          {
                            recommendation.compatibility_level
                          }
                        </span>
                      </td>

                      <td>
                        {new Date(
                          recommendation.created_at
                        ).toLocaleDateString()}
                      </td>
                    </tr>
                  )
                )
              )}
            </tbody>
          </table>
        </div>

        {!loading && (
          <p className={styles.recordCount}>
            Showing {filteredRecommendations.length} of{" "}
            {recommendations.length} recommendation records
          </p>
        )}
      </section>

      {/* Engine Information */}
      <section className={styles.infoCard}>
        <span className={styles.infoCardIcon} aria-hidden="true">
          <SparklesIcon size={24} />
        </span>

        <div>
          <h2>Compatibility Engine</h2>

          <p>
            Recommendations are calculated using the agricultural
            requirements stored in the system. The engine evaluates
            soil, water, sunlight, environment, weather, planting
            season, and location suitability to determine how
            compatible a crop is with the user&apos;s selected conditions.
          </p>

          <p>
            Administrators manage the underlying crop, requirement,
            location, and planting-calendar data. These datasets
            provide the information used by the recommendation engine.
          </p>
        </div>
      </section>
    </div>
  );
}